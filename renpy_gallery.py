"""Conservative, read-only gallery qualification and removable runtime patches.

No game Python is evaluated, no pickle is loaded, and no persistent is edited.
Standard support deliberately requires visible source and a reviewed engine
implementation. Unknown compiled/custom mechanisms fail closed.
"""
