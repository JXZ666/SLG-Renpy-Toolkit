def render(root):
    """Render a deterministic patch for qualified capability, or raise."""
    result = survey(root)
    if not result["supported"]:
        raise ValueError("; ".join(result["reasons"]))
    if result["mechanism"] == "reviewed_replay":
        return _REVIEWED_REPLAY.replace("SCOPE", repr(result["coverage"]["scope"]))
    return _STANDARD.replace("OBJECTS", repr(result["coverage"]["objects"]))
