def _text(path):
    return path.read_text(encoding="utf-8-sig", errors="strict")


def _result(supported=False, mechanism="unsupported", reasons=None, **coverage):
    return {"supported": supported, "mechanism": mechanism,
            "reasons": list(reasons or []), "coverage": coverage}


def _fingerprint(game):
    digest = hashlib.sha256()
    for path in sorted(game.glob("*.rpy")):
        if not path.name.startswith("zz_"):
            digest.update(path.name.encode("utf-8"))
            digest.update(path.read_bytes())
    return digest.hexdigest()


def _assets(game, sources):
    # Only literal image declarations can establish a resource statically.
    found = {}
    for source in sources:
        for name, expr in re.findall(r"(?m)^\s*image\s+([\w ]+?)\s*=\s*([^\n]+)", source):
            try:
                value = ast.literal_eval(expr.split(" #", 1)[0].strip())
            except (ValueError, SyntaxError):
                continue
            if isinstance(value, str):
                found[name.strip()] = value
    return found


def _available(game, ref, assets):
    target = assets.get(ref, ref)
    if target.startswith("#"):
        return True
    path = (game / target).resolve()
    return path.is_relative_to(game.resolve()) and path.is_file()


def _reviewed_replay(game, sources):
    replay_engine = game.parent / "renpy/common/00action_other.rpy"
    if not replay_engine.is_file() or hashlib.sha256(replay_engine.read_bytes()).hexdigest() != _REVIEWED_REPLAY_ENGINE:
        return _result(reasons=["The replay engine implementation has not been reviewed."])
    joined = "\n".join(sources)
    setup = _text(game / "replay_setup.rpy")
    entries = re.findall(r'(?m)^\s*Replay_items\.append\(ReplayItem\(\["([^"]+)"\],\s*"([^"]+)"', setup)
    labels = set(re.findall(r"(?m)^\s*label\s+([\w.]+)\s*(?:\([^\n]*\))?\s*:", joined))
    assets = _assets(game, sources)
    missing_labels = [label for _, label in entries if label not in labels]
    missing_thumbs = [thumb for thumb, _ in entries if not _available(game, thumb, assets)]
    missing_images = [ref for ref in ("img1", "img2") if not _available(game, ref, assets)]
    # Scope is made from existing default variables, not guessed values. Replay
    # uses a fresh context; persistent.name is deliberately never assigned.
    scope = re.findall(r"(?m)^default\s+(\w+)\s*=", _text(game / "script.rpy"))
    reasons = []
    if missing_labels:
        reasons.append("Replay targets are missing (%d)." % len(missing_labels))
    if missing_thumbs:
        reasons.append("Replay thumbnails are missing (%d)." % len(missing_thumbs))
    if missing_images:
        reasons.append("Image gallery contains missing placeholder resources; image unlocking is unavailable.")
    replay = bool(entries and scope and not missing_labels and not missing_thumbs)
    if replay:
        reasons.append("Only the reviewed replay gallery is unlocked; image gallery rules are unchanged.")
    return _result(replay, "reviewed_replay" if replay else "unsupported", reasons,
                   level="partial", gallery_images=False, replay=replay,
                   replay_count=len(entries), scope=scope)


def _standard(game, sources):
    joined = "\n".join(sources)
    names = re.findall(r"(?m)^\s*(\w+)\s*=\s*Gallery\(\s*\)", joined)
    if not names:
        return _result(reasons=["No reviewed standard Gallery construction was found."])
    if re.search(r"\b(?:Replay|GalleryItem|ReplayItem|seen_label|seen_image)\s*\(", joined):
        return _result(reasons=["Custom image/replay lock logic needs a dedicated adapter."])
    assets = _assets(game, sources)
    refs = []
    for name in names:
        # Late label/screen Python must not reintroduce object conditions after
        # our init callback. This first adapter covers init-time declarations.
        for block in re.split(r"(?m)^(?:label|screen)\s+", joined)[1:]:
            if re.search(r"\b" + re.escape(name) + r"\.(?:button|image|unlock|unlock_image|condition|allprior)\s*\(", block):
                return _result(reasons=["Runtime gallery declarations need a dedicated adapter."])
        calls = re.findall(r"\b" + re.escape(name) + r"\.(\w+)\s*\(([^\n]*)\)", joined)
        methods = {method for method, _ in calls}
        if not {"button", "make_button"}.issubset(methods):
            return _result(reasons=["Gallery buttons and their screen have not both been identified."])
        allowed = {"button", "image", "unlock_image", "unlock", "condition", "allprior",
                   "transform", "make_button", "get_fraction", "Action"}
        if methods - allowed or re.search(r"\b" + re.escape(name) + r"\.(?:buttons|button_|image_|unlockable)\b", joined):
            return _result(reasons=["Gallery internals are customized; refusing an unverified override."])
        for method, arguments in calls:
            if method in ("image", "unlock_image", "unlock"):
                try:
                    call = ast.parse("f(" + arguments + ")", mode="eval").body
                    values = [ast.literal_eval(arg) for arg in call.args]
                except (ValueError, SyntaxError):
                    return _result(reasons=["Dynamic gallery resources cannot be verified statically."])
                if not values or not all(isinstance(value, str) for value in values):
                    return _result(reasons=["Nonliteral gallery resources need a dedicated adapter."])
                refs.extend(values)
    # Conditions inside Gallery are overridden locally. Screen-level gates are
    # separate locks and cannot be inferred from the standard object alone.
    screens = re.split(r"(?m)^screen\s+", joined)[1:]
    for screen in screens:
        if any(re.search(r"\b" + re.escape(name) + r"\.", screen) for name in names):
            if re.search(r"(?m)^\s+(?:if|elif|showif)\s+", screen):
                return _result(reasons=["Gallery screen has additional conditional gates."])
    if not refs or any(not _available(game, ref, assets) for ref in refs):
        return _result(reasons=["Gallery image resources are missing or not statically resolvable."])
    return _result(True, "standard_gallery", ["Standard Gallery image/condition/prior locks only; no replay adapter."],
                   level="standard", gallery_images=True, replay=False, objects=sorted(set(names)),
                   image_count=len(refs))


def survey(root):
    """Return supported/mechanism/reasons/coverage without executing game code."""
    root = Path(root)
    game = root / "game"
    try:
        engine = root / "renpy" / "common" / "00gallery.rpy"
        if not engine.is_file() or hashlib.sha256(engine.read_bytes()).hexdigest() not in _ENGINES:
            return _result(reasons=["The Gallery engine implementation has not been reviewed."])
        paths = [path for path in game.rglob("*.rpy")
                 if "tl" not in path.relative_to(game).parts and not path.name.startswith("zz_")]
        sources = [_text(path) for path in paths]
        if _fingerprint(game) == _SAMPLE_B_FINGERPRINT:
            return _reviewed_replay(game, sources)
        if all((game / name).is_file() and hashlib.sha256((game / name).read_bytes()).hexdigest() == digest
               for name, digest in _CUSTOM_COMPILED.items()):
            return _result(False, "custom_gallery_unverified", [
                "Reviewed runtime inventory found 2 standard Gallery entries without object conditions, separate from 59 custom scenes.",
                "Screen-level seen_image/seen_label and persistent.gallery_unlocked gates remain; their replay actions and scoped overrides are not yet adapted."],
                level="unsupported", gallery_images=False, replay=False, custom_scene_count=59)
        if any(path.suffix == ".rpa" for path in game.iterdir()):
            return _result(reasons=["Archived scripts require a reviewed game adapter."])
        if any(not path.with_suffix(".rpy").is_file() for path in game.rglob("*.rpyc")
               if "tl" not in path.relative_to(game).parts and not path.name.startswith("zz_")):
            return _result(reasons=["Compiled scripts have no visible source; their gallery locks are unverified."])
        return _standard(game, sources)
    except (OSError, UnicodeError, ValueError) as exc:
        return _result(reasons=["Gallery inspection failed: %s" % exc])


