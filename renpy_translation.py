def _standard_choice_sources(game):
    """Qualify the SDK's small default choice screen, not arbitrary menus."""
    qualified = []
    for path in sorted(game.rglob("*.rpy")):
        rel = path.relative_to(game)
        if path.name.startswith("zz_") or set(rel.parts) & {"tl", "saves", "cache"}:
            continue
        source = path.read_text(encoding="utf-8-sig", errors="strict")
        lines = source.splitlines()
        for index, line in enumerate(lines):
            if not re.fullmatch(r"screen choice\(items\)\s*:\s*(?:#.*)?", line):
                continue
            body = []
            for following in lines[index + 1:]:
                if following.strip() and not following[0].isspace() and not following.lstrip().startswith("#"):
                    break
                if following.strip() and not following.lstrip().startswith("#"):
                    body.append(following.strip())
            if body == ['style_prefix "choice"', 'vbox:', 'for i in items:', 'textbutton i.caption action i.action']:
                qualified.append((rel.as_posix(), index + 1, hashlib.sha256(path.read_bytes()).hexdigest()))
    return qualified


def survey(root):
    result = {"supported": False, "mechanism": "unsupported", "reasons": [],
              "coverage": {"dialogue": False, "standard_adv_menu": False,
                           "nvl": False, "custom_menu": False}}
    root = Path(root).resolve()
    try:
        pair = tuple(hashlib.sha256((root / rel).read_bytes()).hexdigest() for rel in ENGINE_FILES)
        version = REVIEWED_ENGINES.get(pair)
        if version is None:
            result["reasons"].append("Ren'Py dialogue/menu interfaces are not a reviewed 8.3/8.4 engine build; original text will be kept.")
            return result
        if not (root / "game").is_dir():
            result["reasons"].append("No game directory was found.")
            return result
        choices = _standard_choice_sources(root / "game")
    except (OSError, UnicodeError, ValueError) as exc:
        result["reasons"].append("Translation interface inspection failed: " + type(exc).__name__)
        return result
    result.update(supported=True, mechanism="renpy_loopback_connector", engine_version=version)
    result["coverage"].update(dialogue=True, standard_adv_menu=bool(choices))
    result["reasons"].append("Reviewed Ren'Py " + version + ": executed standard ADV say statements; prediction never requests translation.")
    result["reasons"].append("Default source-visible ADV choice screen is supported." if choices else
                             "Choice screen source is custom or unavailable; menu choices remain in the original language.")
    result["reasons"].append("NVL, custom character/menu paths and external Luna embedding remain outside built-in translation coverage.")
    return result


_CONNECTOR = r'''
import http.client as _http
import json as _json
import os as _os
import re as _re
import sys as _sys
import time as _time
import hashlib as _hashlib

_engine = None
_prior_filter = None
_prior_menu = None
_disabled = False
_cooldown = 0.0
_reported = set()
_endpoint = None
_token = ""
_session = ""
_game = ""
_wait = 2000
_conflict_reported = False

def _log(message):
    if message in _reported:
        return
    _reported.add(message)
    try:
        _engine.exports.log("RPYKIT_TRANSLATION: " + message)
    except Exception:
        pass

def _luna_active():
    try:
        for function in (_engine.text.text.Text.__init__, _engine.text.text.Text.render,
                         _engine.character.display_say):
            values = getattr(function, "__globals__", {})
            if (getattr(function, "_rpykit_luna_bridge", False) or
                    (callable(values.get("callLunaHost")) and callable(values.get("callLunaIsUsingEmbed")))):
                return True
    except Exception:
        return False
    return False

def _ready():
    global _disabled
    if _disabled or _endpoint is None or _time.monotonic() < _cooldown:
        return False
    try:
        if _engine.exports.predicting() or _engine.game.context().init_phase:
            return False
    except Exception:
        return False
    if _luna_active():
        _disabled = True
        _log("External Luna embedding detected; built-in translation stopped to avoid duplicate embedding.")
        _report_luna_conflict()
        return False
    return True

def _read_response(connection, started, budget):
    # Bound the *whole* loopback exchange, including a partial HTTP response.
    # HTTPResponse.read() alone resets a socket timeout for each received part.
    data, header_end, length, status = bytearray(), None, None, None
    while True:
        remaining = budget - (_time.monotonic() - started)
        if remaining <= 0:
            raise TimeoutError("translation deadline")
        connection.sock.settimeout(remaining)
        chunk = connection.sock.recv(65536)
        if not chunk:
            break
        data.extend(chunk)
        if header_end is None:
            position = data.find(b"\r\n\r\n")
            if position < 0:
                if len(data) > 65536:
                    raise ValueError("host headers too large")
                continue
            header_end = position + 4
            lines = bytes(data[:position]).decode("ascii").split("\r\n")
            status = int(lines[0].split(" ")[1])
            for line in lines[1:]:
                name, value = line.split(":", 1)
                if name.lower() == "content-length":
                    length = int(value.strip())
                if name.lower() == "transfer-encoding":
                    raise ValueError("unsupported host transfer encoding")
            if length is not None and not 0 <= length <= 1048576:
                raise ValueError("host response too large")
            if status in (401, 403, 410):
                return status, b""
        if header_end is not None:
            size = len(data) - header_end
            if size > 1048576:
                raise ValueError("host response too large")
            if length is not None and size >= length:
                break
    if header_end is None or (length is not None and len(data) - header_end != length):
        raise ValueError("incomplete host response")
    return status, bytes(data[header_end:])

def _report_luna_conflict():
    global _conflict_reported
    if _conflict_reported or _endpoint is None:
        return
    try:
        if _engine.exports.predicting():
            return
    except Exception:
        return
    _conflict_reported = True
    started, budget, connection = _time.monotonic(), 0.2, None
    try:
        connection = _http.HTTPConnection("127.0.0.1", _endpoint, timeout=budget)
        connection.connect()
        remaining = budget - (_time.monotonic() - started)
        if remaining <= 0:
            return
        connection.sock.settimeout(remaining)
        body = _json.dumps({"session_id": _session, "game_id": _game,
                            "status": "luna_conflict"}).encode("utf-8")
        connection.request("POST", "/status", body=body,
                           headers={"Authorization": "Bearer " + _token, "Content-Type": "application/json"})
        _read_response(connection, started, budget)
    except Exception:
        pass
    finally:
        if connection is not None:
            connection.close()

def _request(texts, kind):
    global _cooldown, _disabled
    if not _ready() or not texts or any(not isinstance(t, str) or len(t) > 65536 for t in texts):
        return list(texts)
    started = _time.monotonic()
    budget = _wait / 1000.0
    # A zero-wait setting cannot wait for a network result. The host does not
    # receive speculative text and the currently executing line stays original.
    if budget <= 0:
        return list(texts)
    connection = None
    try:
        connection = _http.HTTPConnection("127.0.0.1", _endpoint, timeout=min(0.2, budget))
        connection.connect()
        remaining = budget - (_time.monotonic() - started)
        if remaining <= 0:
            return list(texts)
        connection.sock.settimeout(remaining)
        body = _json.dumps({"session_id": _session, "game_id": _game, "texts": list(texts),
                            "kind": kind, "budget_ms": max(0, int(remaining * 1000))}, ensure_ascii=False).encode("utf-8")
        connection.request("POST", "/translate", body=body,
                           headers={"Authorization": "Bearer " + _token, "Content-Type": "application/json"})
        status, payload = _read_response(connection, started, budget)
        if status in (401, 403, 410):
            _disabled = True
            _log("Translation session ended; continuing with original text.")
            return list(texts)
        if status != 200:
            raise ValueError("host response status")
        result = _json.loads(payload.decode("utf-8"))
        values = result.get("results")
        statuses = result.get("statuses")
        if (not isinstance(values, list) or len(values) != len(texts) or
                not isinstance(statuses, list) or len(statuses) != len(texts)):
            raise ValueError("host response shape")
        if _time.monotonic() - started > budget:
            return list(texts)
        return [value if is_safe_translation(original, value) else original
                for original, value in zip(texts, values)]
    except Exception:
        _cooldown = _time.monotonic() + 10.0
        _log("Translation host unavailable or timed out; original text retained (10 second retry cooldown).")
        return list(texts)
    finally:
        if connection is not None:
            connection.close()

def _adv_speaker(who):
    if who is None:
        who = _engine.store.narrator
    if isinstance(who, str):
        return False
    nvl_type = getattr(_engine.store, "NVLCharacter", None)
    if nvl_type is not None and isinstance(who, nvl_type):
        return False
    return (type(who) is _engine.character.ADVCharacter and
            getattr(who, "screen", "say") in (None, "say"))

def _filter(text):
    # Always preserve the game's existing transformation, including in predict
    # and menu AST phases. Only Say.execute is allowed to submit a line.
    if _prior_filter is not None:
        text = _prior_filter(text)
    frame = _sys._getframe(1)
    try:
        if (frame.f_code is not _engine.ast.Say.execute.__code__ or
                not _adv_speaker(frame.f_locals.get("who"))):
            return text
        return _request([text], "say")[0]
    finally:
        del frame

def _default_choice_screen():
    try:
        screen = _engine.display.screen.get_screen_variant("choice")
        if screen is None or screen.ast is None:
            return False
        filename, line = screen.location
        filename = filename.replace("\\", "/")
        filename = filename.split("/game/", 1)[-1]
        if filename.startswith("game/"):
            filename = filename[5:]
        for rel, expected_line, digest in _choices:
            if filename == rel and line == expected_line:
                path = _os.path.join(_engine.config.gamedir, *rel.split("/"))
                with open(path, "rb") as stream:
                    return _hashlib.sha256(stream.read()).hexdigest() == digest
    except Exception:
        pass
    return False

def _menu(items, *args, **kwargs):
    if (not _ready() or not _engine.config.menu_actions or args or kwargs or
            not _default_choice_screen()):
        return _prior_menu(items, *args, **kwargs)
    frame = _sys._getframe(1)
    try:
        # exports.menu performs set/condition filtering and constructs the
        # original ChoiceReturn. Preserve these exact objects and their labels.
        if frame.f_code is not _engine.exports.menu.__code__:
            return _prior_menu(items, *args, **kwargs)
    finally:
        del frame
    menu_args, menu_kwargs = _engine.exports.get_menu_args()
    if (menu_args or any(k not in ("screen",) for k in menu_kwargs) or
            menu_kwargs.get("screen", "choice") != "choice"):
        return _prior_menu(items, *args, **kwargs)
    if any(not isinstance(item, (tuple, list)) or len(item) != 2 or not isinstance(item[0], str)
           or (item[1] is not None and type(item[1]) is not _engine.ui.ChoiceReturn) for item in items):
        return _prior_menu(items, *args, **kwargs)
    translated = _request([item[0] for item in items], "menu")
    return _prior_menu([(label, original[1]) for label, original in zip(translated, items)], *args, **kwargs)

def _restore_menu_hook():
    # store.menu may be restored by loading an old save. Reinstall only over
    # the exact reviewed default; never replace a game's custom menu function.
    if _engine.store.menu is _prior_menu:
        _engine.store.menu = _menu

def install(engine):
    global _engine, _prior_filter, _prior_menu, _endpoint, _token, _session, _game, _wait, _disabled
    _engine = engine
    endpoint = _os.environ.get("RPYKIT_TRANSLATION_URL", "")
    match = _re.fullmatch(r"http://127\.0\.0\.1:(\d{1,5})/translate", endpoint)
    if match is None:
        return
    port = int(match.group(1))
    if not 1 <= port <= 65535:
        return
    _token = _os.environ.get("RPYKIT_TRANSLATION_TOKEN", "")
    _session = _os.environ.get("RPYKIT_TRANSLATION_SESSION", "")
    _game = _os.environ.get("RPYKIT_TRANSLATION_GAME", "")
    if not _token or not _session or not _game:
        return
    try:
        _wait = max(0, min(30000, int(_os.environ.get("RPYKIT_TRANSLATION_WAIT_MS", "2000"))))
        for rel, digest in _engine_hashes:
            with open(_os.path.join(engine.config.basedir, *rel.split("/")), "rb") as stream:
                if _hashlib.sha256(stream.read()).hexdigest() != digest:
                    _log("Engine source changed after connector inspection; original text retained.")
                    return
    except Exception:
        return
    _endpoint = port
    if _luna_active():
        _disabled = True
        _log("External Luna embedding detected; built-in translation not enabled.")
        _report_luna_conflict()
        return
    if getattr(engine.config.say_menu_text_filter, "__module__", "") == __name__:
        return
    _prior_filter = engine.config.say_menu_text_filter
    engine.config.say_menu_text_filter = _filter
    if engine.store.menu is engine.exports.display_menu:
        _prior_menu = engine.store.menu
        engine.store.menu = _menu
        engine.config.after_load_callbacks.append(_restore_menu_hook)
'''


def render(root):
    root = Path(root).resolve()
    found = survey(root)
    if not found["supported"]:
        raise ValueError("; ".join(found["reasons"]))
    hashes = [(rel, hashlib.sha256((root / rel).read_bytes()).hexdigest()) for rel in ENGINE_FILES]
    runtime = (TEXT_RUNTIME + "\n_engine_hashes = " + repr(hashes) +
               "\n_choices = " + repr(_standard_choice_sources(root / "game")) + "\n" + _CONNECTOR)
    # A private ordinary module owns ephemeral endpoint/state. No threads,
    # sockets, service objects, API credentials or module objects enter store.
    bootstrap = '''import sys as _sys
import types as _types
import renpy as _engine
_name = "_rpykit_translation_runtime_v1"
if _name not in _sys.modules:
    _module = _types.ModuleType(_name)
    _sys.modules[_name] = _module
    exec(compile(%r, "<rpykit-translation>", "exec"), _module.__dict__)
    _module.install(_engine)
''' % runtime
    return "# " + MARKER + "\n# Optional, original-text-safe loopback translation connector.\ninit 998 python hide:\n" + textwrap.indent(bootstrap, "    ")
