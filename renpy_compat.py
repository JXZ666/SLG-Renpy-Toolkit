"""Conservative runtime remedies; survey never executes game scripts.

Only a proven custom main-menu entry gets a default-start fallback. A
recognized Luna hook can translate at the say interface so the engine's
Text consistency checks and translated slow/pause ranges remain active.
"""
import os
import re
import hashlib

REL = "zz_rpykit_compat.rpy"
MARKER = "GENERATED BY `rpykit fontfix`"
# Exact engine pair exercised by the real-engine offline Luna probe. Version
# numbers and matching fragments alone cannot prove display_say semantics.
REVIEWED_LUNA_ENGINES = {
    ("99159e1d7551c6df84e3dd6a568688aa20146ac334a3afcc5b1cc8c103d66ccd",
     "6f5815b6b66aa511ecdfa363b8d7ad180870768347581eca44495594f0e7e26d")
}
_LABEL = re.compile(r"^label\s+([A-Za-z_]\w*)\s*(?:\([^\n]*\))?\s*:", re.M)
_SCREEN = re.compile(r"^screen main_menu\([^\n]*\)\s*:\s*\n((?:[ \t]+[^\n]*\n|\n)*)", re.M)
_START = re.compile(r"\baction\s+Start\(\s*(['\"])([A-Za-z_]\w*)\1\s*\)")


def _read(path):
    with open(path, "r", encoding="utf-8-sig", errors="replace") as stream:
        return stream.read()


def _luna_api(root):
    try:
        character = _read(os.path.join(root, "renpy", "character.py"))
        text_engine = _read(os.path.join(root, "renpy", "text", "text.py"))
    except OSError:
        return False
    pair = []
    for rel in ("renpy/character.py", "renpy/text/text.py"):
        with open(os.path.join(root, *rel.split("/")), "rb") as stream:
            pair.append(hashlib.sha256(stream.read()).hexdigest())
    pair = tuple(pair)
    return (pair in REVIEWED_LUNA_ENGINES and all(piece in character for piece in (
        "def display_say(", "class DialogueTextTags", "dtt = DialogueTextTags(what)",
        "if what_text.text[0] == what_string:", "elif renpy.config.developer:"))
        and "def set_text(" in text_engine)


def survey(root):
    result = {"supported": False, "mechanism": None, "reasons": []}
    root = os.path.abspath(os.fspath(root))
    game = os.path.join(root, "game")
    try:
        config = _read(os.path.join(root, "renpy", "config.py"))
        start = _read(os.path.join(root, "renpy", "common", "00start.rpy"))
        if not re.search(r"^label_overrides\s*=", config, re.M):
            result["reasons"].append("Engine has no verified label_overrides API.")
            return result
        if 'renpy.jump("start")' not in start:
            result["reasons"].append("Engine default-start fallback is not verified.")
            return result
        sources = []
        uncertain = False
        for directory, dirs, files in os.walk(game, followlinks=False):
            # Translations do not define the original entry; tool files are
            # excluded so installing this feature cannot change its survey.
            dirs[:] = [d for d in dirs if d not in ("tl", "cache", "saves", "localization")]
            for name in files:
                path = os.path.join(directory, name)
                if name.endswith(".rpa") or (name.endswith(".rpyc") and not os.path.isfile(path[:-1])):
                    if name != REL + "c":
                        uncertain = True
                if name.endswith(".rpy") and name != REL:
                    sources.append(_read(path))
        labels = set()
        entries = set()
        screen_count = 0
        for source in sources:
            labels.update(_LABEL.findall(source))
            for match in _SCREEN.finditer(source):
                screen_count += 1
                entries.update(target for _, target in _START.findall(match.group(1)))
        traceback = os.path.join(root, "traceback.txt")
        if os.path.isfile(traceback) and "was not given the exact contents of the what variable" in _read(traceback):
            result["diagnostics"] = ["luna_text_mismatch"]
            if _luna_api(root):
                result.update(supported=True, mechanism="luna_say_bridge")
                result["reasons"].append("Verified say API; bridge activates only for the recognized Luna Python embedding hook. Real Luna session verification is still required.")
                return result
            result["reasons"].append("Dialogue Text mismatch found, but this engine source pair is not reviewed. A real-engine probe is required before enabling the Luna bridge.")
        if "start" in labels:
            result["reasons"].append("Game already defines start; no entry fallback is needed.")
        elif uncertain:
            result["reasons"].append("Compiled-only or archived scripts prevent proving start is absent.")
        elif screen_count != 1 or len(entries) != 1:
            result["reasons"].append("A unique literal main-menu Start target could not be verified.")
        else:
            target = next(iter(entries))
            if target not in labels:
                result["reasons"].append("Main-menu Start target has no verified label.")
            else:
                result.update(supported=True, mechanism="custom_start_fallback", target=target)
                result["reasons"].append("Missing default start; verified native main-menu target: " + target)
        # This passive bridge is useful even after an old traceback is
        # deleted. It remains inert unless the recognized Luna hook appears.
        if not result["supported"] and _luna_api(root):
            result.update(supported=True, mechanism="luna_say_bridge")
            result["reasons"].append("Verified say API; optional bridge activates only for the recognized Luna embedding hook. It does not repair unverified entry labels.")
    except (OSError, ValueError) as exc:
        result["reasons"].append("Runtime compatibility scan failed: " + str(exc))
    return result


def render(root):
    found = survey(root)
    if not found["supported"]:
        raise ValueError("; ".join(found["reasons"]))
    if found["mechanism"] == "luna_say_bridge":
        return "# " + MARKER + "\n# Recognized Luna hook bridge; developer checks remain enabled.\ninit 999 python:\n" + "".join("    " + line + "\n" for line in LUNA_BODY.splitlines())
    target = found["target"]
    return '''# %s
# Reversible entry fallback. Original game scripts are untouched.
# This does not change dialogue Text or developer error checks.
init 999 python:
    if (not renpy.has_label("start") and
            "start" not in config.label_overrides and
            renpy.has_label("%s")):
        config.label_overrides["start"] = "%s"
''' % (MARKER, target, target)


# https://github.com/HIllya51/LunaTranslator/blob/main/src/NativeImpl/LunaHook/LunaHook/resource/renpy_hook_text.py
# Luna's public resource/renpy_hook_text.py wraps Text.__init__ (split 1)
# and Text.render (split 2). Move embedding upstream for this one say call,
# then keep the host from translating its result twice. The engine computes
# pause/slow ranges from translated DialogueTextTags, without changing Text.
LUNA_BODY = '''import renpy as _rpykit_engine
import re as _rpykit_re
import functools as _rpykit_functools
try:
    _rpykit_string_types = (basestring,)
except NameError:
    _rpykit_string_types = (str,)

def _rpykit_luna_context():
    for method in (_rpykit_engine.text.text.Text.__init__,
                   _rpykit_engine.text.text.Text.render):
        namespace = getattr(method, "__globals__", None)
        if namespace is None:
            namespace = getattr(method, "func_globals", {})
        host = namespace.get("callLunaHost")
        embed = namespace.get("callLunaIsUsingEmbed")
        original = namespace.get("original_Text_init_hook")
        if (callable(host) and callable(embed) and callable(original) and
                getattr(method, "__name__", "") == "new_init"):
            return namespace, host, embed
    return None

def _rpykit_wrap_say(original):
    @_rpykit_functools.wraps(original)
    def bridge(who, what, *args, **kwargs):
        context = _rpykit_luna_context()
        if context is None:
            return original(who, what, *args, **kwargs)
        namespace, host, embed = context
        split = 1 if embed(1) else (2 if embed(2) else None)
        if split is None or not isinstance(what, _rpykit_string_types):
            return original(who, what, *args, **kwargs)
        translated = host(what, split)
        if not isinstance(translated, _rpykit_string_types) or translated == what:
            return original(who, what, *args, **kwargs)
        # A translator must preserve Ren'Py control/formatting tags. Never
        # manufacture a pause schedule for changed or missing control tags.
        tags = r"(?<!\\{)\\{[^{}]*\\}"
        if _rpykit_re.findall(tags, what) != _rpykit_re.findall(tags, translated):
            return original(who, what, *args, **kwargs)
        dtt = _rpykit_engine.character.DialogueTextTags(translated)
        protected = (translated, dtt.text)
        def protected_host(text, requested_split):
            if text in protected:
                return text
            return host(text, requested_split)
        # display_say's dtt is keyword-only in the verified engine. Preserve
        # all remaining display arguments and let the real engine run its
        # comparison, slow text, callbacks, CTC and interaction normally.
        kwargs["dtt"] = dtt
        namespace["callLunaHost"] = protected_host
        try:
            return original(who, translated, *args, **kwargs)
        finally:
            if namespace.get("callLunaHost") is protected_host:
                namespace["callLunaHost"] = host
    bridge._rpykit_luna_bridge = True
    return bridge

if not getattr(_rpykit_engine.character.display_say, "_rpykit_luna_bridge", False):
    _rpykit_engine.character.display_say = _rpykit_wrap_say(
        _rpykit_engine.character.display_say)
'''
