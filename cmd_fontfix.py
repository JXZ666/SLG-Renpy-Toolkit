def _asset(name):
    """A bundled data file, both from source and from a frozen build.

    A one-file build extracts itself to sys._MEIPASS and points __file__ in
    there, so resolving assets from HERE alone would lose the font exactly
    when the tool is shipped.
    """
    return os.path.join(getattr(sys, "_MEIPASS", None) or HERE, "assets", name)


