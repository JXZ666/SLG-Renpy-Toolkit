"""What rpykit-luna installs into a Ren'Py game, and the runner that does it.

The tool applies one or more *features* to a game folder, each an independent
change with its own generated file and its own undo. The catalogue lives in
features.py; this module implements them and runs them. There are two today:

  fontfix  `zz_localization.rpy` points every font name the game resolves at a
           FontGroup that keeps the original face for Latin and draws CJK with
           the bundled Noto, plus the font itself under game/localization/.
           A game that renders Chinese as tofu (empty boxes) has a font
           problem, not a translation problem - and every Chinese string,
           whether from a tl/ block or injected into the text box at runtime by
           an external translator, is drawn with whatever font the current
           style names. Fixing the font once makes all of those paths work.
           This is why it is a pre-flight step and not part of translating.

  intro    `zz_rpykit_intro.rpy` points the game's `splashscreen` label at a
           no-op, so the opening logos stop being part of every launch. It is a
           separate file from the shim because it is a different class of
           change - the shim only ADDS aliases, while this one displaces a
           label the game defines - and because it has to be revertible alone.

Two modes, and they must not be mixed on one install:

  luna  Fonts only. Nothing about language or tl/ is touched, so the game keeps
        showing its own text and an external translator is free to swap the
        text in at runtime. This is the pre-flight mode.

  full  Fonts plus `config.language`, for when rpykit itself installed a
        translation and the game should start in Chinese.

Installing both would make the game render rpykit's Chinese first and then have
the external tool translate that Chinese into Chinese again.

Nothing here edits a game script or repacks an archive. Every write is
recorded in install_manifest.json and undone by `rpykit-luna --revert`.
"""

