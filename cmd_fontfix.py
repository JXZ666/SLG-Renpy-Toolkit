# Ren'Py's stock defaults. Every gui.rpy defines gui.text_font and friends from
# these names, so they are aliased even when a scan misses the literal.
BASELINE_FACES = ["DejaVuSans.ttf", "DejaVuSans-Bold.ttf"]

# Ren'Py draws emoji and the accessibility font through their own mechanisms,
# so aliasing these would break features rather than fix them. Matched on the
# lowercased stem, because the extension-less safety net below also produces
# names like "TwemojiCOLRv0" that must be caught by the same rule.
NEVER_ALIAS_STEMS = {"twemojicolrv0", "_opendyslexic3-regular"}

LATIN_FULL = (0x0000, 0x2E7F)
LATIN_ASCII = (0x0020, 0x007E)

SHIM = string.Template('''\
########################################################################
# zz_localization.rpy - font glue for Chinese text
#
# GENERATED BY `rpykit fontfix` - do not hand-edit, it will be regenerated.
# Undo with:  rpykit-luna --revert
#
# Non-destructive. This file only ADDS behaviour on top of the shipped game;
# it never edits a game script and never repacks an archive.
#
# The faces this game ships contain no CJK Hanzi, so Chinese drawn with them
# comes out as tofu (the empty-box characters). Each font name the game
# resolves is pointed at a FontGroup that keeps the original face for Latin
# and hands everything CJK to the font installed alongside this file.
#
# Generated: $stamp
# Game:      $game_dir
# Mode:      $mode
$table_comment
########################################################################

init 999 python:
$language_block
    # Ren'Py searches "localization/..." with the loader prefixes ["", "fonts/"]
    # (renpy/text/font.py:648), so this resolves next to this rpy file.
    _loc_cjk = "$cjk_path"

    def _loc_group(latin_face, lo, hi):
        """A FontGroup: `latin_face` for one Latin range, Noto for CJK.

        A FontGroup is not a font file. Ren'Py splits each rendered string by
        codepoint and draws each run with whichever font claims it, and the
        first add() to claim a codepoint wins - so ranges are added
        narrowest-first and the bare (None, None) default goes last.

        `latin_face` is None when the original face does not have complete
        Latin coverage. Delegating a range to a face that cannot fill it
        produces blanks, which is worse than losing the styling.

        Note the signature of FontGroup.add: end is a required positional and
        is ignored only when start is None. Passing two arguments raises
        `TypeError: add() missing 1 required positional argument: 'end'`.
        """
        group = FontGroup()

        if latin_face:
            group.add(latin_face, lo, hi)

        group.add(_loc_cjk, 0x3000, 0x30FF)     # CJK punctuation, kana
        group.add(_loc_cjk, 0x3400, 0x4DBF)     # CJK Extension A
        group.add(_loc_cjk, 0x4E00, 0x9FFF)     # CJK Unified Ideographs
        group.add(_loc_cjk, 0xF900, 0xFAFF)     # CJK Compatibility Ideographs
        group.add(_loc_cjk, 0xFE10, 0xFE4F)     # CJK Compatibility Forms
        group.add(_loc_cjk, 0xFF00, 0xFFEF)     # Halfwidth and Fullwidth Forms
        group.add(_loc_cjk, 0x20000, 0x2FA1F)   # CJK Extensions B onwards
        group.add(_loc_cjk, None, None)         # default for everything else

        return group

    # (alias, delegating Latin face or None, delegate from, delegate to)
    _loc_faces = [
$faces
    ]

    # Pass 1 builds every group before anything is aliased, because
    # FontGroup.add() refuses a face whose name is already a registered alias.
    # Aliasing during the build would break the second name delegating to the
    # first. Groups are memoised on the delegation config so that names which
    # resolve to the same face share one object: a group materialises a
    # codepoint entry per covered character, so one per name would be several
    # megabytes each.
    _loc_cache = {}
    _loc_built = []
    for _loc_name, _loc_latin, _loc_lo, _loc_hi in _loc_faces:
        _loc_key = (_loc_latin, _loc_lo, _loc_hi)
        if _loc_key not in _loc_cache:
            try:
                _loc_cache[_loc_key] = _loc_group(_loc_latin, _loc_lo, _loc_hi)
            except Exception:
                # Either the game already aliased this name or the face cannot
                # be loaded. Noto-only still renders Chinese; it just drops the
                # original styling, which beats an init-time crash on startup.
                _loc_cache[_loc_key] = _loc_group(None, 0, 0)
        _loc_built.append((_loc_name, _loc_cache[_loc_key]))

    # Pass 2 publishes them. config.font_name_map is consulted wherever a font
    # *name* is resolved: style definitions, style inheritance and inline
    # {font=...} tags (renpy/text/text.py lines 254, 296 and 1395). That covers
    # every font the game hardcodes, including ones baked into dialogue.
    for _loc_name, _loc_group_obj in _loc_built:
        config.font_name_map[_loc_name] = _loc_group_obj
''')

